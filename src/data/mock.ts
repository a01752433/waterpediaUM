const seasonOf = (iso: string): SamplePoint["season"] => {
  const month = Number(iso.slice(5, 7));
  if (month >= 11 || month <= 3) return "Monsoon";
  if (month >= 6 && month <= 9) return "Dry";
  return "Transition";
};

const round = (n: number) => Math.round(n * 10) / 10;

function buildSeries(
  wqi0: number,
  do0: number,
  nh30: number,
  cod0: number,
  drift: number,
): SamplePoint[] {
  return MONTHS.map((date, i) => {
    const wave = Math.sin(i / 2.2) * 3.2;
    const monsoonDip = seasonOf(date) === "Monsoon" ? -4.5 : seasonOf(date) === "Dry" ? 2.2 : 0;
    const wqi = Math.min(96, Math.max(28, wqi0 + drift * i + wave + monsoonDip));
    return {
      date,
      wqi: round(wqi),
      do: round(Math.max(1.2, do0 + drift * 0.08 * i + wave * 0.08 + (seasonOf(date) === "Monsoon" ? -0.6 : 0.2))),
      nh3: round(Math.max(0.02, nh30 - drift * 0.01 * i + (seasonOf(date) === "Monsoon" ? 0.08 : -0.02))),
      cod: round(Math.max(4, cod0 - drift * 0.3 * i + (seasonOf(date) === "Monsoon" ? 4 : -1))),
      bod: date.startsWith("2025-11") ? null : round(Math.max(0.6, (100 - wqi) / 18)),
      season: seasonOf(date),
    };
  });
}


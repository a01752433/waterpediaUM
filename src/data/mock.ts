export const classRank: Record<NwqsClass, number> = { I: 1, II: 2, III: 3, IV: 4, V: 5 };

export function stationById(id: string) {
  return stations.find((s) => s.id === id);
}

export function classDropped(station: Station) {
  return classRank[station.klass] > classRank[station.previousClass];
}

export function doBelowClassII(station: Station) {
  return station.fresh && station.params.do < 5;
}

